func main() {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by go generate ./extras/kitex; DO NOT EDIT.\n\n")
	buf.WriteString("package kitex\n\n")
	buf.WriteString("import (\n")
	buf.WriteString("\t\"github.com/masterkeysrd/kite/dom\"\n")
	buf.WriteString("\t\"github.com/masterkeysrd/kite/event\"\n")
	buf.WriteString("\t\"github.com/masterkeysrd/kite/geom\"\n")
	buf.WriteString("\t\"github.com/masterkeysrd/kite/style\"\n")
	buf.WriteString(")\n\n")

	for _, s := range specs {
		fmt.Fprintf(&buf, "// %s\n", s.doc)
		fmt.Fprintf(&buf, "type %s struct {\n", s.name)
		for _, f := range baseFields {
			fmt.Fprintf(&buf, "\t%s %s\n", f.name, f.typ)
		}
		for _, f := range s.custom {
			fmt.Fprintf(&buf, "\t%s %s\n", f.name, f.typ)
		}
		buf.WriteString("}\n\n")

		fmt.Fprintf(&buf, "func (p %s) elementProps() ElementProps {\n", s.name)
		buf.WriteString("\treturn ElementProps{\n")
		for _, f := range baseFields {
			fmt.Fprintf(&buf, "\t\t%s: p.%s,\n", f.name, f.name)
		}
		buf.WriteString("\t}\n")
		buf.WriteString("}\n\n")

		fmt.Fprintf(&buf, "func (p %s) getRefSetter() refSetter {\n", s.name)
		buf.WriteString("\treturn p.Ref\n")
		buf.WriteString("}\n\n")

		fmt.Fprintf(&buf, "func (p %s) withStyle(s style.Style) %s {\n", s.name, s.name)
		buf.WriteString("\tp.Style = s\n")
		buf.WriteString("\treturn p\n")
		buf.WriteString("}\n\n")
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		fmt.Fprintf(os.Stderr, "format.Source failed: %v\n", err)
		os.Exit(1)
	}

	if err := os.WriteFile("props_gen.go", formatted, 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "WriteFile failed: %v\n", err)
		os.Exit(1)
	}
}
